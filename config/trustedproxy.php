<?php

/*
|--------------------------------------------------------------------------
| Доверенные прокси
|--------------------------------------------------------------------------
|
| Middleware TrustProxies читает список доверенных адресов из этого файла и
| только после этого начинает уважать заголовки X-Forwarded-*.
|
| Зачем это нужно: когда перед приложением стоит reverse proxy (nginx, Caddy)
| и TLS заканчивается на нём, приложение получает обычный HTTP. Без доверия к
| прокси Laravel считает запрос небезопасным: ссылки генерируются с http,
| сессионная cookie не получает флаг Secure.
|
| По умолчанию доверенных прокси нет: приложение никого не слушает, кроме
| самого прокси, который вы настроили сами. Укажите адрес или '*' (доверять
| всем), если приложение доступно только через ваш proxy.
|
*/

$proxies = env('TRUSTED_PROXIES');

return [
    'proxies' => match (true) {
        $proxies === null, $proxies === '' => null,
        $proxies === '*' => '*',
        default => array_values(array_filter(array_map('trim', explode(',', (string) $proxies)))),
    },
];
