    | карточки и внутренние ajax-методы (/maps/api/business/...).
    |
    */

    'base_url' => env('YANDEX_MAPS_BASE_URL', 'https://yandex.ru/maps'),

    'locale' => env('YANDEX_MAPS_LOCALE', 'ru_RU'),

    /*
    |--------------------------------------------------------------------------
    | Постраничная выгрузка отзывов
    |--------------------------------------------------------------------------
    |
    | Яндекс отдаёт отзывы страницами по 50 штук и обрывает выдачу примерно
    | на 600 отзывах (проверено: страница 13 приходит пустой даже при 5859
