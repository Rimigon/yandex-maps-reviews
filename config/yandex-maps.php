    |
    */

    'cache_ttl' => (int) env('YANDEX_MAPS_CACHE_TTL', 900),

    /*
    |--------------------------------------------------------------------------
    | Очередь фоновой выгрузки
    |--------------------------------------------------------------------------
    |
    | Имя очереди, в которую попадают задания на выгрузку. Позволяет держать
    | отдельный пул воркеров под парсинг и не тормозить остальные задачи.
    |
    */

    'queue' => env('YANDEX_MAPS_QUEUE', 'default'),

    /*
    |--------------------------------------------------------------------------
    | Запасной путь: headless-браузер
